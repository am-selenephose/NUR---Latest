export function normalizeLocale(raw: string | null | undefined): SupportedLocale {
  const value = (raw ?? "en").trim();
  if (SUPPORTED_LOCALES.includes(value as SupportedLocale)) return value as SupportedLocale;
  const base = value.split("-")[0];
  if (base === "zh") return "zh-Hans";
  if (SUPPORTED_LOCALES.includes(base as SupportedLocale)) return base as SupportedLocale;
  return "en";
}

export function resolveWritingPreference(locale: SupportedLocale, requested: WritingPreference | null | undefined): WritingPreference {
  const variants = LOCALE_VARIANTS[locale] as readonly WritingPreference[];
  const value = requested ?? variants[0];
  if (value === "default" && !variants.includes("default")) return variants[0];
  if (!variants.includes(value)) throw new RangeError(`Writing preference ${value} is not supported for ${locale}`);
  return value;
}

export function directionFor(locale: SupportedLocale, preference: WritingPreference): TextDirection {
  if (locale === "ur" && preference === "roman") return "ltr";
  return LOCALE_DIRECTIONS[locale];
}
